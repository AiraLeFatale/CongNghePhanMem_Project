import {
  ArrowDown,
  ArrowRight,
  ArrowUp,
  CaretRight,
  CheckCircle,
  ChartBar,
  DotsSixVertical,
  DownloadSimple,
  FileText,
  Globe,
  House,
  List,
  MagnifyingGlass,
  MapPin,
  MapTrifold,
  PencilSimple,
  Plus,
  Printer,
  QrCode,
  SignOut,
  SpeakerHigh,
  Translate,
  Trash,
  User,
  Wallet,
  Warning,
  X,
  type Icon as PhosphorIcon,
} from '@phosphor-icons/react';

const ICONS: Record<string, PhosphorIcon> = {
  home: House,
  pin: MapPin,
  route: MapTrifold,
  qr: QrCode,
  chart: ChartBar,
  user: User,
  logout: SignOut,
  plus: Plus,
  menu: List,
  trash: Trash,
  edit: PencilSimple,
  download: DownloadSimple,
  print: Printer,
  up: ArrowUp,
  down: ArrowDown,
  grip: DotsSixVertical,
  globe: Globe,
  speaker: SpeakerHigh,
  x: X,
  search: MagnifyingGlass,
  file: FileText,
  caret: CaretRight,
  arrow: ArrowRight,
  translate: Translate,
  warning: Warning,
  wallet: Wallet,
  check: CheckCircle,
};

export function Icon({ name, size = 16, className, weight = 'regular' }: { name: string; size?: number; className?: string; weight?: 'regular' | 'bold' | 'fill' }) {
  const Glyph = ICONS[name];
  if (!Glyph) return null;
  return <Glyph className={`icon${className ? ` ${className}` : ''}`} size={size} weight={weight} aria-hidden="true" focusable="false" />;
}
